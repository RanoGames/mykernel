/* gdt.h — Global Descriptor Table: описывает сегменты памяти (код/данные),
 * которыми пользуется процессор.
 *
 * ЗАЧЕМ ЭТО НУЖНО, если GRUB уже настраивает какую-то GDT сама:
 * GDT, которую даёт GRUB (или упрощённый загрузчик QEMU при "-kernel"),
 * ВРЕМЕННАЯ и предназначена только на время работы самого GRUB. Она
 * может быть недостаточно строгой (у QEMU) или лежать в памяти, судьбу
 * которой ядро не контролирует (у настоящего GRUB). Как только ядро
 * начинает само работать с сегментными регистрами (а наши обработчики
 * прерываний в isr.s именно это и делают), полагаться на чужую
 * временную таблицу — плохая идея: в лучшем случае "случайно работает",
 * в худшем — исключение General Protection Fault, которое, если сама
 * обработка прерываний из-за той же причины тоже сломана, перерастает
 * в Double Fault, а затем в Triple Fault — аппаратный сброс процессора
 * (то самое "комп бесконечно перезагружается").
 *
 * Поэтому один из первых шагов любого "настоящего" ядра — создать
 * СВОЮ GDT и явно на неё переключиться. */

