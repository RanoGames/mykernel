/* boot.s — точка входа в ядро и Multiboot-заголовок для GRUB.
 * GRUB ищет этот заголовок в первых 8 КБ файла ядра, чтобы понять,
 * как его загружать (Multiboot v1 — самый простой и совместимый вариант). */

/* Константы для заголовка Multiboot (см. спецификацию Multiboot 1) */
.set ALIGN,    1<<0             /* выравнивать загружаемые модули по границе страницы */
.set MEMINFO,  1<<1             /* просить у GRUB карту памяти */
.set FLAGS,    ALIGN | MEMINFO  /* итоговые флаги заголовка */
.set MAGIC,    0x1BADB002       /* магическое число, по которому GRUB опознаёт Multiboot */
.set CHECKSUM, -(MAGIC + FLAGS) /* контрольная сумма: MAGIC+FLAGS+CHECKSUM должно давать 0 */

/* Сам Multiboot-заголовок кладём в отдельную секцию .multiboot,
 * которую линкер разместит в самом начале файла (см. linker.ld).
 * Флаг "a" (alloc) обязателен: имя секции нестандартное, и без
 * явного флага ассемблер не помечает её как "загружаемую в память",
 * из-за чего линкер размещает её некорректно (проверено на практике —
 * без этого флага сборка "работает", но GRUB/QEMU не находят заголовок). */
.section .multiboot, "a"
.align 4
    .long MAGIC
    .long FLAGS
    .long CHECKSUM

/* Резервируем место под стек ядра.
 * На старте процессора стека ещё нет — его нужно создать самим.
 * Стек растёт вниз, поэтому "верх" стека — это конец зарезервированной области. */
.section .bss
.align 16
stack_bottom:
    .skip 16384   /* 16 КБ на стек — с запасом для простого ядра */
stack_top:

/* Точка входа, которую вызывает GRUB.
 * На момент вызова: защищённый режим включён, пейджинг выключен,
 * прерывания выключены, сегменты настроены GRUB-ом на "плоскую" модель. */
.section .text
.global _start
.type _start, @function
_start:
    /* Устанавливаем указатель стека на вершину нашего стека */
    mov $stack_top, %esp

    /* На случай, если понадобится — GRUB кладёт в ebx указатель на
     * multiboot-информацию (карта памяти и т.д.), а в eax — магическое
     * число 0x2BADB002, подтверждающее загрузку через Multiboot.
     * Пока это не используется, но передаём в стек на будущее. */
    push %ebx
    push %eax

    /* Вызываем главную функцию ядра, написанную на C */
    call kernel_main

    /* Если kernel_main вдруг вернёт управление — вешаем процессор
     * в бесконечном цикле, чтобы не улететь в случайный код */
    cli                 /* запретить прерывания */
hang:
    hlt                 /* остановить процессор до следующего прерывания */
    jmp hang            /* на случай "ложного" прерывания — зацикливаемся снова */

.size _start, . - _start
