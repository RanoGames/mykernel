/* calc.h — вычислитель простых арифметических выражений: + - * / ^ и
 * скобки, с правильным приоритетом операций (сначала ^, потом * и /,
 * потом + и -). Степень правоассоциативна: 2^3^2 = 512. */

#ifndef CALC_H
#define CALC_H

/* Вычисляет выражение из строки expr (например "2 + 3 * (4 - 1)" или "2^8").
 * Возвращает результат. Если в строке ошибка (недопустимый символ,
 * незакрытая скобка, отрицательная степень и т.п.) или было деление на 0 —
 * устанавливает *out_error = 1, иначе 0. */
long calc_eval(const char* expr, int* out_error);

#endif
