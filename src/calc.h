/* calc.h — вычислитель простых арифметических выражений: + - * / и
 * скобки, с правильным приоритетом операций (сначала * и /, потом
 * + и -), как в обычном калькуляторе. */

#ifndef CALC_H
#define CALC_H

/* Вычисляет выражение из строки expr (например "2 + 3 * (4 - 1)").
 * Возвращает результат. Если в строке ошибка (недопустимый символ,
 * незакрытая скобка и т.п.) или было деление на 0 — устанавливает
 * *out_error = 1, иначе 0. */
long calc_eval(const char* expr, int* out_error);

#endif
