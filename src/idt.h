/* idt.h — Interrupt Descriptor Table: таблица, которая говорит процессору,
 * какую функцию вызывать при каждом прерывании/исключении (их 256 штук). */

#ifndef IDT_H
#define IDT_H

#include <stdint.h>

/* Один элемент (дескриптор) таблицы прерываний.
 * __attribute__((packed)) — запрещаем компилятору добавлять выравнивание
 * между полями, т.к. процессор ожидает строго такой бинарный формат. */
struct idt_entry {
    uint16_t base_low;    /* младшие 16 бит адреса обработчика */
    uint16_t sel;         /* селектор сегмента кода (из GDT, GRUB даёт нам 0x08) */
    uint8_t  always0;     /* всегда 0 */
    uint8_t  flags;       /* тип дескриптора + уровень привилегий + бит "присутствует" */
    uint16_t base_high;   /* старшие 16 бит адреса обработчика */
} __attribute__((packed));

/* Указатель на таблицу для инструкции lidt: размер таблицы - 1 и адрес */
struct idt_ptr {
    uint16_t limit;
    uint32_t base;
} __attribute__((packed));

void idt_init(void);
/* Регистрирует функцию-обработчик под конкретным номером прерывания.
 * Используется модулем IRQ, чтобы подключить обработчик клавиатуры и т.п. */
void idt_set_gate(uint8_t num, uint32_t handler, uint16_t sel, uint8_t flags);

#endif
