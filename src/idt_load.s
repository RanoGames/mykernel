/* idt_load.s — выполняет инструкцию lidt.
 * Инструкцию lidt нельзя вызвать напрямую из C, поэтому здесь простая
 * ассемблерная функция-обёртка, вызываемая как обычная C-функция. */

.section .text
.global idt_load
.type idt_load, @function

idt_load:
    mov 4(%esp), %eax   /* забираем единственный аргумент функции (адрес idt_ptr) из стека */
    lidt (%eax)         /* говорим процессору использовать эту таблицу прерываний */
    ret

.size idt_load, . - idt_load
