/* serial.h — драйвер последовательного порта COM1 (UART 16550).
 *
 * ЗАЧЕМ ЭТО НУЖНО: обычно наше ядро выводит текст через видеопамять
 * VGA (0xB8000), и это видно в графическом окне QEMU. Но если у вас
 * не получается увидеть это окно (проблемы с рендерингом WSLg,
 * драйверами видеокарты и т.п.), COM-порт — это способ получить тот
 * же вывод текстом прямо в терминале, без всякого графического окна:
 *
 *   qemu-system-i386 -kernel build/mykernel.bin -nographic
 *
 * Флаг -nographic говорит QEMU не открывать графическое окно вообще,
 * а подключить порт COM1 виртуальной машины прямо к текущему
 * терминалу — всё, что ядро пишет в serial_write(), появится у вас
 * в консоли как обычный текст. */

#ifndef SERIAL_H
#define SERIAL_H

void serial_init(void);
void serial_write(const char* data);
void serial_putchar(char c);

/* Проверить, пришёл ли байт от того, кто печатает в терминал с другой
 * стороны serial-соединения (в нашем случае — сам QEMU при запуске
 * с флагом -nographic, куда попадает всё, что вы печатаете в консоли
 * WSL). Не блокирует выполнение — просто говорит, есть данные или нет. */
int serial_has_data(void);

/* Прочитать один уже пришедший байт. Вызывать только после того, как
 * serial_has_data() вернула не 0 — иначе можно "зависнуть" в ожидании
 * байта, которого нет (эта функция блокирующая). */
char serial_read_char(void);

#endif
