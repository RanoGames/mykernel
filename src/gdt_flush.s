/* gdt_flush.s — загружает новую GDT инструкцией lgdt и заставляет
 * процессор реально начать её использовать.
 *
 * Загрузить GDT инструкцией lgdt недостаточно: сегментные регистры
 * (cs, ds, es, fs, gs, ss) хранят не только "номер" сегмента, но и
 * закэшированную процессором копию его свойств (базы/лимита/прав),
 * загруженную В МОМЕНТ, когда в регистр в последний раз что-то
 * записывали. Поэтому после lgdt нужно ЗАНОВО записать значения во
 * все сегментные регистры, чтобы они перечитали данные уже из новой
 * таблицы. Для cs это можно сделать только через "дальний" переход
 * (far jump) — обычным mov в cs процессор не позволяет. */

.section .text
.global gdt_flush
.type gdt_flush, @function

gdt_flush:
    mov 4(%esp), %eax   /* забираем аргумент функции (адрес gdt_ptr) из стека */
    lgdt (%eax)         /* говорим процессору использовать эту GDT */

    /* Перезагружаем сегменты данных: 0x10 — селектор нашего сегмента
     * данных ядра (2-й дескриптор в таблице, индекс считается от 0,
     * умноженный на 8 байт на дескриптор = смещение 0x10) */
    mov $0x10, %ax
    mov %ax, %ds
    mov %ax, %es
    mov %ax, %fs
    mov %ax, %gs
    mov %ax, %ss

    /* Перезагружаем cs через дальний переход на следующую же инструкцию,
     * но уже с новым селектором кода 0x08 (1-й дескриптор в таблице) */
    ljmp $0x08, $.flush_done
.flush_done:
    ret

.size gdt_flush, . - gdt_flush
