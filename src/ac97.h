/* ac97.h — драйвер звуковой карты Intel AC'97 (PCI audio, класс 0x04/0x01).
 *
 * AC97 — это стандартный PCI-аудиочип, эмулируемый QEMU по умолчанию
 * почти на любой машине (Vendor 0x8086 "Intel", разные Device ID
 * в зависимости от чипсета — обычно 0x2415 для 82801AA). Устройство
 * состоит из двух функциональных блоков, каждый со своим BAR:
 *
 *   BAR0 (NAM  — Native Audio Mixer)  : регистры для управления
 *                                        громкостью, включения выхода
 *   BAR1 (NABM — Native Audio Bus Master) : регистры DMA-движка,
 *                                        который САМ (без процессора)
 *                                        читает из памяти и шлёт
 *                                        сэмплы на выход
 *
 * Как работает воспроизведение звука через DMA, коротко:
 *  1. Готовим в памяти сам звук (массив 16-битных сэмплов).
 *  2. Готовим отдельную структуру — "Buffer Descriptor List" (BDL):
 *     до 32 записей вида {физический адрес буфера, длина, флаги}.
 *     Это способ сказать контроллеру: "вот список кусков памяти,
 *     проиграй их по очереди".
 *  3. Пишем физический адрес BDL в регистр контроллера (BDBAR).
 *  4. Говорим контроллеру, сколько записей списка использовать (LVI)
 *     и командуем "начать" (бит RUN в регистре управления).
 *  5. Дальше контроллер САМ, через DMA, читает наш буфер из памяти
 *     и отправляет звук на выход — процессор в этом не участвует,
 *     именно поэтому это называется DMA (Direct Memory Access) —
 *     "прямой доступ к памяти" в обход CPU. */

#ifndef AC97_H
#define AC97_H

#include <stdint.h>

/* Инициализация: ищет AC97 на шине PCI, включает Bus Mastering,
 * настраивает микшер на разумную громкость. Возвращает 1 при успехе,
 * 0 если устройство не найдено (например, QEMU запущен без звуковой
 * карты — тогда просто аккуратно ничего не делаем дальше). */
int ac97_init(void);

/* Есть ли рабочая звуковая карта (после ac97_init) */
int ac97_is_present(void);

/* Проиграть буфер 16-битных стерео-сэмплов (44100 Гц, как обычный
 * несжатый WAV) через DMA. Вызов блокирующий: возвращается, когда
 * воспроизведение действительно закончилось (ждём через опрос
 * регистра текущей позиции — без обработчика прерывания для простоты).
 * samples       — указатель на массив int16_t (пары left,right)
 * sample_count  — количество ОТДЕЛЬНЫХ 16-битных чисел в массиве
 *                 (то есть для N стерео-фреймов это 2*N) */
void ac97_play(const int16_t* samples, uint32_t sample_count);

/* Сгенерировать и проиграть простой синусоидальный тон — самый
 * простой способ проверить, что DMA реально работает, без файлов
 * и файловой системы (команда `beep97` в shell) */
void ac97_play_test_tone(uint32_t freq_hz, uint32_t duration_ms);

#endif
